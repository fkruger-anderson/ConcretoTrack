package br.com.anderson.meuprimeiroprojeto

import org.junit.Test

import org.junit.Assert.*

/**
 * Teste de exemplo criado automaticamente pelo Android Studio junto com o projeto.
 *
 * Fica na pasta `src/test`, que é a dos testes "unitários": rodam direto no computador, sem
 * celular, e por isso são muito rápidos. O plano de testes do projeto está em
 * `docs/plano-de-testes.md`.
 */
class ExampleUnitTest {
    /**
     * `@Test` marca a função como um teste. O `assertEquals(esperado, obtido)` confere se os dois
     * valores são iguais; se não forem, o teste falha e mostra a diferença.
     */
    @Test
    fun addition_isCorrect() {
        assertEquals(4, 2 + 2)
    }
}
